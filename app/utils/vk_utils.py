import re
from typing import Union


class VkUtils:
    @staticmethod
    def is_valid_vk_id(vk_id: str) -> bool:
        """
        Проверяет, является ли строка корректным VK ID.

        Правила для VK ID:
        - Может быть числовым (например: 123456789)
        - Может быть строковым (например: id123456789 или durov)
        - Не может быть пустым
        - Не может содержать пробелы
        - Минимальная длина: 1 символ (для строковых ID)
        """
        if not vk_id:
            return False

        # Проверка на наличие пробелов
        if " " in vk_id:
            return False

        # Проверка на допустимые символы
        # Разрешены: латиница, цифры, нижнее подчеркивание, точка, дефис
        # Также допустим префикс 'id' перед цифрами
        pattern = r"^(?:id)?[a-zA-Z0-9._-]+$"

        if not re.match(pattern, vk_id):
            return False

        # Дополнительные проверки
        # Если ID начинается с 'id', то после должны идти только цифры
        if vk_id.startswith("id"):
            rest = vk_id[2:]
            if rest and not rest.isdigit():
                return False

        # Проверка максимальной длины (обычно VK ID не длиннее 50 символов)
        return not len(vk_id) > 50

    @staticmethod
    def is_valid_chat_id(chat_id: Union[str, int]) -> bool:
        """
        Проверяет, является ли значение корректным Chat ID для Telegram.

        Правила для Chat ID:
        - Может быть положительным числом (для обычных пользователей)
        - Может быть отрицательным числом (для групп, каналов, супергрупп)
        - Может быть числом с префиксом '-100' (для супергрупп и каналов)
        - Может быть строковым представлением числа
        - Не может быть пустым
        - Не может содержать буквы или спецсимволы (кроме знака минус в начале)

        Примеры корректных Chat ID:
        - 123456789 (положительный)
        - -123456789 (отрицательный)
        - -1001234567890 (супергруппа/канал)
        - "123456789" (строковое представление)
        - "-1001234567890" (строковое представление)

        Примеры НЕкорректных Chat ID:
        - "" (пустая строка)
        - "abc123" (содержит буквы)
        - "123 456" (содержит пробел)
        - "-" (только минус)
        - "123.456" (содержит точку)
        """
        if chat_id is None:
            return False

        # Преобразуем в строку для проверки
        chat_id_str = str(chat_id).strip()

        # Проверка на пустое значение
        if not chat_id_str:
            return False

        # Проверка на наличие пробелов
        if " " in chat_id_str:
            return False

        # Проверка на допустимые символы: только цифры и знак минус в начале
        # Разрешаем только: ^-?\d+$ (опциональный минус в начале и цифры)
        pattern = r"^-?\d+$"

        if not re.match(pattern, chat_id_str):
            return False

        # Дополнительные проверки
        try:
            # Пробуем преобразовать в число
            chat_id_int = int(chat_id_str)

            # Проверка на диапазон значений
            # В Telegram Chat ID может быть в диапазоне от -2^63 до 2^63-1
            if chat_id_int < -9223372036854775808 or chat_id_int > 9223372036854775807:
                return False

            # Проверка на слишком длинное число (обычно не более 19 цифр)
            if len(chat_id_str) > 19:
                return False

            # Проверка на специальные форматы
            # Для супергрупп и каналов: начинается с -100
            if chat_id_str.startswith("-100"):
                # После -100 должны быть цифры (как минимум 1)
                rest = chat_id_str[4:]
                if not rest or not rest.isdigit():
                    return False

            return True

        except ValueError:
            # Если не удалось преобразовать в число
            return False
